def allocate_lonlat(grid, lon, lat, cat):
    r"""Allocate a category for given locations in a grid.

    Parameters
    ----------
    grid : ndarray
        Original grid.
    lon : list of int
        Longitude index for the category to be applied.
    lat : list of list of int
        Latitude index for the category to be applied. The length of the main
        list should match that of lon.
    cat : int
        Category number.
    """
    for n, i in enumerate(lon):
        for j in range(lat[n][0], lat[n][1]+1):
            v = grid[j, i]
            if not np.isfinite(v) or v == 0.:
                grid[j, i] = cat
            else:
                print(f"Conflict ({v}, {cat}) at ({j}, {i})")


